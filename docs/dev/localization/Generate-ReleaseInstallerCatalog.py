#!/usr/bin/env python3
"""Generate self-contained 1.6 Setup UI display resources from the reviewed source catalogs.

Dev-only generator. Output is C# (no runtime JSON dependency). Fail closed on
schema, parameter or key drift; Installer/Setup transaction code is untouched.
"""
import json
import re
import sys
from pathlib import Path

ROOT=Path(__file__).resolve().parents[3]
LANG=ROOT/"Source"/"lang"
OUTPUT=ROOT/"Installer"/"RdcReleaseUiCatalog.Generated.cs"
PREFIXES=("installer.maintenance.","installer.path.","installer.legacy.")
KEY_RE=re.compile(r"\Ainstaller\.(?:maintenance|path|legacy)\.[A-Za-z][A-Za-z0-9]*\Z")
PARAM_RE=re.compile(r"\{[A-Za-z][A-Za-z0-9]*\}")
# {error} is legacy-only staging; the new release UI never formats raw exceptions.
ALLOWED_PARAMS={"version","installedVersion","targetVersion","error"}
def load(locale):
 data=json.loads((LANG/(locale+".json")).read_text(encoding="utf-8-sig"))
 assert data["schema"]=="rdc-relay-i18n-v1" and data["locale"]==locale
 assert data["status"]=="INTEGRATION_TEST", "RELEASE_I18N_UNREVIEWED_DICTIONARY_REQUIRED"
 pairs={k:v for k,v in data["strings"].items() if k.startswith(PREFIXES)}
 assert len(pairs)==36,(locale,"EXPECTED_36_KEYS",len(pairs))
 for k,v in pairs.items():
  assert KEY_RE.fullmatch(k)
  assert isinstance(v,str) and 0<len(v)<=600
  assert not re.search(r"[\x00-\x08\x0b\x0c\x0e-\x1f]",v)
 return pairs
ru,en=load("ru-RU"),load("en-US")
assert ru.keys()==en.keys()
for key in ru:
 a=set(PARAM_RE.findall(ru[key]));b=set(PARAM_RE.findall(en[key]))
 assert a==b and all(x[1:-1] in ALLOWED_PARAMS for x in a),("PARAMS_MISMATCH",key,a,b)
 assert ru[key].count("{")==len(a) and ru[key].count("}")==len(a),("RU_PLACEHOLDER_INVALID",key)
 assert en[key].count("{")==len(b) and en[key].count("}")==len(b),("EN_PLACEHOLDER_INVALID",key)
def encode(s):
 # ASCII C# string escape representation: JSON escapes work for C# for this bounded catalog.
 return json.dumps(s,ensure_ascii=True)
lines=[
 "// AUTOGENERATED by docs/dev/localization/Generate-ReleaseInstallerCatalog.py",
 "// RDC Relay 1.6 release Setup-only texts. No dev files are included at runtime.",
 "// WARNING: translations are INTEGRATION_TEST and require editorial approval before release.",
 "using System;",
 "using System.Collections.Generic;",
 "",
 "internal static class RdcReleaseUiCatalog {",
]
for locale,var,items in (("ru-RU","Russian",ru),("en-US","English",en)):
 lines.append(" internal static readonly IDictionary<string,string> "+var+" =")
 lines.append("  new Dictionary<string,string>(StringComparer.Ordinal){")
 for k,v in sorted(items.items()):
  lines.append("   {"+encode(k)+","+encode(v)+"},")
 lines.append("  };")
lines.append("}")
rendered="\n".join(lines)+"\n"
if "--check" in sys.argv:
 assert OUTPUT.exists() and OUTPUT.read_text(encoding="utf-8")==rendered, "GENERATED_INSTALLER_CATALOG_STALE"
 print("PASS_INSTALLER_CATALOG_REPRODUCIBLE keys=36 each_locale")
else:
 OUTPUT.write_text(rendered,encoding="utf-8")
 print("PASS_INSTALLER_CATALOG_GENERATED keys=36 each_locale source=Source/lang")
